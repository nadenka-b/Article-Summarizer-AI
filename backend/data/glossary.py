# Менеджер глоссария
# ============================================================================
class GlossaryManager:
    """Импорт и поиск терминов глоссария в БД (идемпотентно)."""

    async def insert_in_session(
        self,
        session: AsyncSession,
        entry: Dict[str, Any],
    ) -> Optional[str]:
        """
        Вставляет запись с ON CONFLICT (field, term) DO NOTHING.

        Возвращает id новой записи или None, если термин уже есть.
        """
        dialect = session.bind.dialect.name if session.bind else "sqlite"

        if dialect == "postgresql":
            stmt = (
                pg_insert(GlossaryDB)
                .values(**entry)
                .on_conflict_do_nothing(
                    index_elements=["field", "term"],
                )
                .returning(GlossaryDB.id)
            )
        else:
            stmt = (
                sqlite_insert(GlossaryDB)
                .values(**entry)
                .on_conflict_do_nothing(
                    index_elements=["field", "term"],
                )
                .returning(GlossaryDB.id)
            )

        result = await session.execute(stmt)
        return result.scalar_one_or_none()

    async def add_many(
        self,
        session: AsyncSession,
        entries: Sequence[Dict[str, Any]],
    ) -> tuple[int, int]:
        """Добавляет записи; возвращает (added, skipped)."""
        added = 0
        skipped = 0
        for entry in entries:
            new_id = await self.insert_in_session(session, entry)
            if new_id is not None:
                added += 1
            else:
                skipped += 1
        await session.flush()
        return added, skipped

    async def count(self, session: AsyncSession) -> int:
        result = await session.execute(select(func.count(GlossaryDB.id)))
        return result.scalar_one()

    async def search_terms(
        self,
        session: AsyncSession,
        query: str,
        limit: int = 10,
    ) -> List[GlossaryDB]:
        """Поиск терминов по подстроке (без учёта регистра)."""
        stmt = (
            select(GlossaryDB)
            .where(GlossaryDB.term.ilike(f"%{query}%"))
            .order_by(func.length(GlossaryDB.term))
            .limit(limit)
        )
        result = await session.execute(stmt)
        return list(result.scalars().all())
