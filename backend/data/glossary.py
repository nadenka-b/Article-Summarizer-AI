def _expand(
    rows: List[tuple[str, str, str]],
    category: str,
    language: str = "ru",
) -> List[Dict[str, Any]]:
    return [
        {
            "term": term,
            "definition": definition,
            "category": category,
            "field": field,
            "language": language,
        }
        for term, definition, field in rows
    ]


def _expand_abbrev(rows: List[tuple[str, str, str]]) -> List[Dict[str, Any]]:
    # rows: (term, definition, field)
    return [
        {
            "term": term,
            "definition": definition,
            "category": "abbreviation",
            "field": field,
            "language": "ru",
        }
        for term, definition, field in rows
    ]


def _expand_templates(rows: List[tuple[str, str, str]]) -> List[Dict[str, Any]]:
    # rows: (phrase, purpose, field)
    return [
        {
            "term": phrase,
            "definition": purpose,
            "category": "template",
            "field": field,
            "language": "ru",
        }
        for phrase, purpose, field in rows
    ]


